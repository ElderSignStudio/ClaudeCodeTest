import {
	propagationForestFor,
	findUserInForest,
	type PropagationForest,
	type PropagationUser,
} from '$lib/mock/propagation';
import type {
	UserSignalTree,
	SignalTreeSignalNode,
} from '$lib/mock/userSignalTree';
import type { UserDetail } from '$lib/mock/users';

/*
	Inspector data model.

	The User Signal Tree mounts a unified `PropagationForest` whose
	internal scouts are GENERATED by `propagationForestFor()` from the
	signal item id — they are NOT the mock SignalTreeSignalNode.children
	(those mocks describe the user's editorial "signature signals", not
	the live propagation graph).

	Selection lookup therefore has to walk the PropagationForest, not
	the mock tree. We expose `buildUnifiedForest()` as the single source
	of truth: both `UserSignalTree.svelte` and the page-level inspector
	call it with the same `UserSignalTree` input and get the same
	`PropagationForest` back (deterministic — `propagationForestFor()`
	is hash-seeded from the item id, so the forest is stable across
	mounts).
*/

export type Selection =
	| { kind: 'none' }
	| { kind: 'origin'; rootUser: PropagationUser }
	| {
			kind: 'signal';
			/** Full mock SignalTreeSignalNode — has title, artist, status,
			 *  badges, tags, listeners, generations, etc. */
			signal: SignalTreeSignalNode;
			/** Same node viewed inside the PropagationForest — has the
			 *  actual scout subtree the user is looking at. */
			forestNode: PropagationUser;
	  }
	| {
			kind: 'scout';
			scout: PropagationUser;
			/** The depth-1 ancestor mapped back to its editorial signal
			 *  mock — used to label "Discovered through". */
			parentSignal: SignalTreeSignalNode;
			parentSignalNode: PropagationUser;
			/** Depth from the origin scout. Origin = 0, signal = 1, top-
			 *  level scout under signal = 2, etc. */
			depth: number;
	  };

/*
	Build the unified PropagationForest for a user's signal tree.

	Mirrors the construction in `UserSignalTree.svelte` exactly. Both
	consumers call this so we have a single source of truth and the
	forest is identical between the tree's render and the inspector's
	selection lookup. `propagationForestFor()` is deterministic
	(hash-seeded on item id), so the synthetic scouts (Daria, Renan,
	etc.) are stable.
*/
export function buildUnifiedForest(tree: UserSignalTree): PropagationForest {
	const rootUserId = tree.root.id;

	const itemChildren: PropagationUser[] = [...tree.root.children]
		.sort((a, b) => b.impact - a.impact)
		.map((signal): PropagationUser => {
			const signalForest = propagationForestFor(signal.itemId, signal.listeners, rootUserId);
			const rebranded = findUserInForest(signalForest, rootUserId);
			const downstream = rebranded ? rebranded.children : signalForest.roots;
			return {
				id: signal.itemId,
				name: signal.title,
				avatar: signal.coverArt,
				character: signal.artist,
				branchSize: signal.impact,
				amplifications: signal.generations,
				discoveredAgo: '',
				behaviorNote: '',
				scenes: signal.tags,
				children: downstream,
			};
		});

	const danNode: PropagationUser = {
		id: rootUserId,
		name: tree.root.name,
		avatar: tree.root.avatar,
		character: tree.root.role,
		amplifications: itemChildren.length,
		branchSize: 0,
		discoveredAgo: '',
		behaviorNote: '',
		scenes: [],
		children: itemChildren,
		isOrigin: true,
		isCurrentUser: true,
		nodeKind: 'successful-amplifier',
	};

	/* Recompute branchSize bottom-up for everything EXCEPT item nodes
	   (whose branchSize is the editorial impact score). */
	function annotateUnderItem(u: PropagationUser): number {
		let n = 0;
		for (const c of u.children) n += 1 + annotateUnderItem(c);
		u.branchSize = n;
		return n;
	}
	for (const item of itemChildren) {
		for (const child of item.children) annotateUnderItem(child);
	}
	let danReach = 0;
	for (const item of itemChildren) {
		let itemDownstream = 0;
		for (const child of item.children) itemDownstream += 1 + child.branchSize;
		danReach += 1 + itemDownstream;
	}
	danNode.branchSize = danReach;

	return {
		itemId: `user-tree-${rootUserId}`,
		roots: [danNode],
		hiddenRootUsers: [],
		hiddenRoots: 0,
		totalReach: danReach,
		independentOrigins: 1,
		weightedImpact: 0,
		totalAmplifications: itemChildren.length,
		summary: '',
		branchSummaries: [],
		scenes: [],
		crossingNote: '',
		originNote: '',
	};
}

/** Walk the forest and return the path from a root to the node with
 *  this id, inclusive. `null` if not found. */
function findUserPath(
	forest: PropagationForest,
	id: string,
): PropagationUser[] | null {
	function walk(user: PropagationUser, trail: PropagationUser[]): PropagationUser[] | null {
		const next = [...trail, user];
		if (user.id === id) return next;
		for (const child of user.children) {
			const inner = walk(child, next);
			if (inner) return inner;
		}
		return null;
	}
	for (const root of forest.roots) {
		const hit = walk(root, []);
		if (hit) return hit;
	}
	return null;
}

export function resolveSelection(
	tree: UserSignalTree,
	forest: PropagationForest,
	nodeId: string | null,
): Selection {
	if (!nodeId) return { kind: 'none' };

	if (nodeId === tree.root.id) {
		const root = findUserInForest(forest, nodeId);
		return root ? { kind: 'origin', rootUser: root } : { kind: 'none' };
	}

	const signalMock = tree.root.children.find((s) => s.itemId === nodeId);
	if (signalMock) {
		const node = findUserInForest(forest, nodeId);
		return node ? { kind: 'signal', signal: signalMock, forestNode: node } : { kind: 'none' };
	}

	const path = findUserPath(forest, nodeId);
	if (path && path.length >= 3) {
		/* path = [Dan, signalForestNode, ...intermediates, scout]
		   path[0] = Dan (origin) — depth 0
		   path[1] = signal       — depth 1
		   path[n] = scout        — depth n */
		const signalNode = path[1];
		const parentSignal = tree.root.children.find((s) => s.itemId === signalNode.id);
		if (!parentSignal) return { kind: 'none' };
		return {
			kind: 'scout',
			scout: path[path.length - 1],
			parentSignal,
			parentSignalNode: signalNode,
			depth: path.length - 1,
		};
	}
	return { kind: 'none' };
}

/* ── Metric helpers (forest-based) ────────────────────────── */

/** Total user descendants under a PropagationUser (recursive). */
export function countDescendants(user: PropagationUser): number {
	let n = 0;
	for (const c of user.children) n += 1 + countDescendants(c);
	return n;
}

/** Direct children count (one level only). */
export function directChildrenCount(user: PropagationUser): number {
	return user.children.length;
}

/** Total users reached across all scout subtrees beneath ALL signals
 *  in the rendered forest. */
export function totalDownstreamFromForest(forest: PropagationForest): number {
	const dan = forest.roots[0];
	if (!dan) return 0;
	let n = 0;
	for (const signalNode of dan.children) {
		for (const top of signalNode.children) n += 1 + countDescendants(top);
	}
	return n;
}

/** Average count of user descendants per signal (rounded). */
export function averageBranchSize(forest: PropagationForest): number {
	const dan = forest.roots[0];
	if (!dan || dan.children.length === 0) return 0;
	const total = dan.children.reduce(
		(sum, signal) => sum + signal.children.reduce((a, c) => a + 1 + countDescendants(c), 0),
		0,
	);
	return Math.round(total / dan.children.length);
}

/** The signal mock with the highest impact in this tree. */
export function strongestSignalInTree(tree: UserSignalTree): SignalTreeSignalNode | null {
	if (tree.root.children.length === 0) return null;
	return [...tree.root.children].sort((a, b) => b.impact - a.impact)[0];
}

/** Top-level amplifier of a signal — the direct child with the
 *  largest subtree (forest-derived, so it matches what the user
 *  sees in the tree). */
export function topAmplifier(signalNode: PropagationUser): PropagationUser | null {
	if (signalNode.children.length === 0) return null;
	return [...signalNode.children].sort(
		(a, b) => countDescendants(b) - countDescendants(a),
	)[0];
}

/** Deepest descendant depth under the given signal forest node.
 *  Depth measured from the SIGNAL as 0: a top-level scout is 1, etc. */
export function deepestBranchDepth(signalNode: PropagationUser): number {
	function walk(user: PropagationUser, d: number): number {
		if (user.children.length === 0) return d;
		let max = d;
		for (const c of user.children) {
			const inner = walk(c, d + 1);
			if (inner > max) max = inner;
		}
		return max;
	}
	return walk(signalNode, 0);
}

/** Distinct "character" roles across a signal's downstream scouts. */
export function distinctCharacterCount(signalNode: PropagationUser): number {
	const seen = new Set<string>();
	function walk(user: PropagationUser) {
		if (user.character) seen.add(user.character);
		for (const c of user.children) walk(c);
	}
	for (const c of signalNode.children) walk(c);
	return seen.size;
}

/* ── Editorial bullets ───────────────────────────────────────
   Each "why this matters" generator returns 1–3 short bullets,
   purely derived from the available data. Keep them short,
   observational, and avoid marketing language. */

export function trustBullets(user: UserDetail, tree: UserSignalTree): string[] {
	const bullets: string[] = [];
	if (user.hitRate >= 35) {
		bullets.push('Finds signals before they become obvious.');
	}
	const scenes = user.sceneFootprint.length;
	if (scenes >= 3) {
		bullets.push(
			`Bridges ${scenes} scenes — ${user.sceneFootprint
				.slice(0, 2)
				.map((s) => s.name.toLowerCase())
				.join(' and ')} the strongest.`,
		);
	}
	const multiGen = tree.root.children.filter((s) => s.generations >= 3).length;
	if (multiGen > 0) {
		bullets.push(
			`${multiGen} ${multiGen === 1 ? 'seed' : 'seeds'} grew into multi-generation branches.`,
		);
	}
	return bullets.slice(0, 3);
}

export function signalContextBullets(
	signal: SignalTreeSignalNode,
	signalNode: PropagationUser,
): string[] {
	const bullets: string[] = [];
	if (signal.generations >= 3) {
		bullets.push(`Propagated across ${signal.generations} generations downstream.`);
	}
	const distinctChars = distinctCharacterCount(signalNode);
	if (distinctChars >= 3) {
		bullets.push(`Carried into ${distinctChars} different scout roles.`);
	}
	const top = topAmplifier(signalNode);
	if (top && countDescendants(top) >= 2) {
		bullets.push(`${top.name} carried the strongest single branch.`);
	}
	return bullets.slice(0, 3);
}

export function scoutContextBullets(
	scout: PropagationUser,
	parentSignal: SignalTreeSignalNode,
): string[] {
	const bullets: string[] = [];
	const direct = scout.children.length;
	const total = countDescendants(scout);
	if (direct >= 2) {
		bullets.push(
			`Created ${direct} downstream ${direct === 1 ? 'branch' : 'branches'} from this signal.`,
		);
	}
	if (total > direct && total >= 3) {
		bullets.push(`Propagation continued ${total - direct} steps beyond direct listeners.`);
	}
	const character = scout.character?.toLowerCase() ?? '';
	if (character.includes('bridge')) {
		bullets.push('Bridged the signal into an adjacent scene.');
	} else if (character.includes('branch-defining')) {
		bullets.push(`Defined one of ${parentSignal.title}'s main branches.`);
	}
	return bullets.slice(0, 3);
}

/* ── Status helpers ────────────────────────────────────────── */

export function liveStatusChipClass(status: SignalTreeSignalNode['status']): string {
	switch (status) {
		case 'Accelerating':
			return 'border-[oklch(0.86_0.12_60)]/40 text-[oklch(0.86_0.12_60)]/88 bg-[oklch(0.86_0.12_60)]/10';
		case 'Branch forming':
			return 'border-accent/48 text-accent/92 bg-accent/10';
		case 'Still moving':
			return 'border-accent/30 text-accent/78 bg-accent/6';
		case 'Quiet':
			return 'border-white/14 text-base-content/55 bg-white/3';
		case 'Dormant':
			return 'border-white/8 text-base-content/40 bg-transparent';
	}
}
